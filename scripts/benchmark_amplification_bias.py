#!/usr/bin/env python3
"""Benchmark the MDA GC-bias model against published virome measurements.

ViroForge models phi29/MDA GC bias as a Gaussian on genome GC content:

    efficiency = exp(-15 * gc_bias_strength * (gc - optimal_gc)^2)   [floor 0.001]

Two things need justification: where the peak sits (``optimal_gc``, currently
0.40) and how sharply efficiency falls away from it (``gc_bias_strength``,
currently 3.0).

Calibration target
------------------
Parras-Moltó et al. 2018, Microbiome 6:119 (PMID 29954453, PMC6022446) compared
amplified and unamplified saliva DNA viromes. Two findings are usable here:

1. Shape and peak. "MDA induces systematic bias against DNA molecules with
   extremely low and high GC content, and in turn, over-amplification of contigs
   with average %GC in the range of 45-60%." A symmetric peak is the right form,
   but it sits near 52%, not 40%. They also report under-representation above
   60% GC and, for one protocol, below 40%.

2. Magnitude. Relative to the unamplified virome, MDA produced 6.2% (MDA_T1) and
   7.6% (MDA_G1) of contigs with fold change >10x or <0.1x, falling to 4.5% and
   6% within 35-65% GC once small circular genomes were excluded.

That second number is the benchmark. Note it is an upper bound for the GC term
alone: their measured fold changes also contain stochastic amplification noise
and over-amplification of small circular genomes, which ViroForge models
separately. A GC term that on its own puts more than ~6% of genomes past 10x is
too strong.

Because the generator renormalises abundances after applying efficiency
(``biased / biased.sum()``), only the spread of efficiency matters, not its
absolute level. Fold change is computed the same way here.

Usage
-----
    python scripts/benchmark_amplification_bias.py
    python scripts/benchmark_amplification_bias.py --collections 1 5 9
"""

from __future__ import annotations

import argparse
import sqlite3
from pathlib import Path

import numpy as np

# Published target: proportion of contigs beyond 10x / 0.1x under MDA.
PUBLISHED_BIASED_FRACTION = (0.045, 0.076)
PUBLISHED_OPTIMAL_GC = (0.45, 0.60)

DB = Path(__file__).parent.parent / "viroforge" / "data" / "viral_genomes.db"

# Representative contaminant GC values, as generated by core/contamination.py.
CONTAMINANT_GC = {
    "host_dna (human)": 0.41,
    "rRNA": 0.55,
    "reagent bacteria": 0.50,
    "PhiX174": 0.448,
}


def efficiency(gc: np.ndarray, strength: float, optimal: float = 0.40) -> np.ndarray:
    """The model in viroforge/amplification.py MDAAmplification."""
    return np.maximum(0.001, np.exp(-15.0 * strength * (gc - optimal) ** 2))


def fold_changes(gc: np.ndarray, abundance: np.ndarray, strength: float,
                 optimal: float) -> np.ndarray:
    """Post-amplification / pre-amplification relative abundance, renormalised."""
    eff = efficiency(gc, strength, optimal)
    biased = abundance * eff
    biased /= biased.sum()
    return biased / abundance


def load(cid: int) -> tuple[str, np.ndarray, np.ndarray]:
    con = sqlite3.connect(DB)
    name = con.execute(
        "SELECT collection_name FROM body_site_collections WHERE collection_id=?",
        (cid,)).fetchone()[0]
    rows = con.execute(
        "SELECT g.gc_content, c.relative_abundance "
        "FROM genomes g JOIN collection_genomes c ON g.genome_id=c.genome_id "
        "WHERE c.collection_id=? AND g.gc_content IS NOT NULL", (cid,)).fetchall()
    con.close()
    gc = np.array([r[0] for r in rows], dtype=float)
    ab = np.array([r[1] for r in rows], dtype=float)
    if gc.max() > 1.0:
        gc = gc / 100.0
    ab = ab / ab.sum()
    return name, gc, ab


def biased_fraction(gc, ab, strength, optimal) -> float:
    fc = fold_changes(gc, ab, strength, optimal)
    return float(np.mean((fc > 10) | (fc < 0.1)))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--collections", type=int, nargs="+",
                    default=[1, 5, 9, 13, 16],
                    help="collection ids to test (default: gut, marine, wastewater, "
                         "respiratory RNA, vaginal)")
    ap.add_argument("--strengths", type=float, nargs="+",
                    default=[0.5, 1.0, 1.5, 2.0, 3.0, 3.5])
    args = ap.parse_args()

    lo, hi = PUBLISHED_BIASED_FRACTION
    data = [load(c) for c in args.collections]

    print("=" * 78)
    print("PART 1  Theoretical fold-bias vs the 40% GC optimum")
    print("=" * 78)
    hdr = "  GC%  " + "".join(f"  s={s:<6}" for s in args.strengths)
    print(hdr)
    for gcv in (0.25, 0.30, 0.40, 0.50, 0.60, 0.70):
        cells = "".join(f"  {1/efficiency(np.array([gcv]), s)[0]:>7.1f}x" for s in args.strengths)
        print(f"  {gcv*100:>4.0f} {cells}")
    print("\n  Real genomes span this whole range: DB GC is p1=29% to p99=68%.")

    print()
    print("=" * 78)
    print("PART 2  Genomes past 10x / 0.1x, vs published MDA (4.5-7.6%)")
    print("=" * 78)
    print(f"  {'collection':<34}" + "".join(f"  s={s:<5}" for s in args.strengths))
    for (name, gc, ab), cid in zip(data, args.collections):
        cells = ""
        for s in args.strengths:
            f = biased_fraction(gc, ab, s, 0.40)
            mark = "*" if lo <= f <= hi else " "
            cells += f"  {f*100:>5.1f}%{mark}"
        print(f"  c{cid:<3}{name[:30]:<31}{cells}")
    print("  * within the published 4.5-7.6% band")
    print("  NOTE: an upper bound. The published figure also contains stochastic")
    print("  noise and circular-genome bias, which ViroForge models separately,")
    print("  so the GC term alone should land at or below this band.")

    print()
    print("=" * 78)
    print("PART 3  Peak position: code uses 40%, paper reports 45-60%")
    print("=" * 78)
    print("  The paper reports MDA OVER-amplifies 45-60% GC. Any penalty above 1x")
    print("  in that band is the wrong direction, whatever the strength.\n")
    print(f"  {'optimal':>8} {'s':>5}   " + "".join(f"{int(g*100)}%GC   " for g in (0.45, 0.50, 0.55, 0.60)))
    for opt in (0.40, 0.52):
        for s in (1.5, 3.0):
            cells = "".join(f"{1/efficiency(np.array([g]), s, opt)[0]:>6.2f}x "
                            for g in (0.45, 0.50, 0.55, 0.60))
            flag = "  <- current" if opt == 0.40 and s == 3.0 else ""
            print(f"  {opt:>8.2f} {s:>5}   {cells}{flag}")

    print("\n  Biased fraction over a (optimal_gc, strength) grid, mean/worst across")
    print("  collections, against the published 4.5-7.6%:\n")
    print(f"  {'optimal':>8} " + "".join(f"  s={s:<9}" for s in args.strengths))
    for opt in (0.40, 0.45, 0.50, 0.52, 0.55):
        row = ""
        for s in args.strengths:
            fr = [biased_fraction(gc, ab, s, opt) for _, gc, ab in data]
            row += f"  {np.mean(fr)*100:>4.1f}/{max(fr)*100:>4.1f}  "
        print(f"  {opt:>8.2f} {row}")
    print("   (mean/worst %; worst is usually marine, the widest GC range)")

    print()
    print("=" * 78)
    print("PART 4  Effect on the viral:contaminant ratio")
    print("=" * 78)
    print("  apply_amplification() runs on viral AND contaminant sequences, so")
    print("  gc_bias_strength silently moves contamination fractions too.")
    name, gc, ab = data[0]
    print(f"\n  Contaminant efficiency relative to the median viral genome ({np.median(gc)*100:.0f}% GC), c{args.collections[0]}:")
    for s in args.strengths:
        med = efficiency(np.array([np.median(gc)]), s, 0.40)[0]
        cells = "  ".join(f"{k.split()[0]}={efficiency(np.array([v]), s, 0.40)[0]/med:>5.2f}x"
                          for k, v in CONTAMINANT_GC.items())
        print(f"    s={s:<5} {cells}")

    print()
    print("=" * 78)
    print("VERDICT")
    print("=" * 78)
    fracs = {s: np.mean([biased_fraction(gc, ab, s, 0.40) for _, gc, ab in data])
             for s in args.strengths}
    ok = [s for s, f in fracs.items() if f <= hi]
    print(f"  Mean biased fraction across {len(data)} collections:")
    for s, f in fracs.items():
        print(f"    s={s:<5} {f*100:>5.1f}%   {'within/below published' if f <= hi else 'EXCEEDS published'}")
    print(f"\n  Consistent with published MDA: {ok if ok else 'none tested'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
